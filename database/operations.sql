CREATE TABLE IF NOT EXISTS review_records (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, article_id BIGINT NOT NULL, actor_id BIGINT NOT NULL,
 from_status VARCHAR(16) NOT NULL, to_status VARCHAR(16) NOT NULL, reason VARCHAR(300) NOT NULL DEFAULT '',
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(article_id) REFERENCES articles(id), FOREIGN KEY(actor_id) REFERENCES users(id)
);
CREATE TABLE IF NOT EXISTS admin_logs (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, actor_id BIGINT NOT NULL, action VARCHAR(40) NOT NULL,
 target_id BIGINT NOT NULL, reason VARCHAR(300) NOT NULL DEFAULT '', created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(actor_id) REFERENCES users(id)
);
CREATE TABLE IF NOT EXISTS publication_events (
 article_id BIGINT PRIMARY KEY, first_published_at DATETIME NOT NULL,
 FOREIGN KEY(article_id) REFERENCES articles(id), INDEX(first_published_at)
);
